export interface AchievementItem {
  id: string;
  title: string;        // 成就名稱 (口語化)
  description: string;  // 成就達成說明
}

export interface CategoryDialogue {
  // 1. 正常簡介台詞庫 (懸停 1~3 次時隨機播放，不連續重複)
  normal: string[];

  // 2. 吐槽/微惱台詞庫 (懸停 4~6 次時隨機播放)
  tease: string[];

  // 3. 極度傲嬌/暴躁台詞庫 (懸停 7~9 次時隨機播放)
  tsundere: string[];

  // 4. 第 10 次懸停逃跑前的「最後遺言」 (觸發專屬逃跑動畫前顯示)
  escapeQuote: string;

  // 5. 逃跑後原地留下的小紙條留言
  noteMessage: string;

  // 6. 小紙條上的專屬彩蛋跳轉連結 (點擊後在新分頁打開的趣味網址)
  easterEggLink: {
    text: string;   // 連結按鈕顯示文字
    url: string;    // 跳轉網址
  };

  // 7. 點擊卡片跳轉進入專欄時的短暫確認文字 (彩蛋)
  enterActionText: string;

  // 8. 專屬情緒圖示 (極度傲嬌時替換原本圖示)
  angryIcon: string;

  // 9. 哄回來時的專屬賦歸台詞 (在氣泡短暫展示)
  returnQuote: string;

  // 10. 賦歸時的專屬圖示
  returnIcon: string;
}

